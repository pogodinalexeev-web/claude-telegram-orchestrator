def _drop_lines(text, *prefixes):
    """Выкидывает из блока строки по началу — так гасятся пункты внутри общего
    блока (например строка про календарь в списке порядка маркеров)."""
    keep = [ln for ln in text.splitlines(keepends=True)
            if not ln.lstrip().startswith(prefixes)]
    return "".join(keep)


