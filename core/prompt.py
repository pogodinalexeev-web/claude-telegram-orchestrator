_PERSONA_SLOTS = ("identity", "capture", "longform")
_PERSONA_HEADING_RE = re.compile(r"^##\s+(\S+)\s*$")


def load_persona(cfg, log=None):
    """Читает файл личности и разбирает его на слоты «## имя».

    Нет файла — не беда: ядро соберёт промпт без личности (у нового хозяина
    файл появится после первого разговора). Заголовки-слоты фиксированы,
    всё до первого заголовка (шапка, комментарии) в промпт не попадает."""
    path = Path(cfg["persona_path"])
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as e:
        if log:
            log(f"persona: {path} не читается ({e.strerror}) — промпт без личности")
        return {}
    out, slot, buf = {}, None, []
    for line in text.splitlines():
        m = _PERSONA_HEADING_RE.match(line)
        if m:
            if slot:
                out[slot] = "\n".join(buf).strip("\n")
            slot, buf = m.group(1), []
            continue
        if slot is not None:
            buf.append(line)
    if slot:
        out[slot] = "\n".join(buf).strip("\n")
    return {k: v for k, v in out.items() if k in _PERSONA_SLOTS and v.strip()}


